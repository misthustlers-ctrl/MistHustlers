import nodemailer from "nodemailer";

const SERVICE_TIER_LABELS = {
  starter: "STARTER (₹999 – ₹4,999)",
  growth: "GROWTH (₹5,000 – ₹15,000)",
  premium: "PREMIUM (₹15,000 – ₹50,000+)",
};

export function getMailIntegrationStatus() {
  const missing = ["SMTP_EMAIL", "SMTP_PASSWORD", "EMAIL_TO"].filter((key) => !process.env[key]);
  return {
    configured: missing.length === 0,
    missing,
    from: process.env.SMTP_EMAIL ? process.env.SMTP_EMAIL.replace(/(^.).*(@.*$)/, "$1***$2") : null,
    to: process.env.EMAIL_TO ? process.env.EMAIL_TO.replace(/(^.).*(@.*$)/, "$1***$2") : null,
  };
}

function createMailTransporter() {
  const status = getMailIntegrationStatus();
  if (!status.configured) {
    const err = new Error(`SMTP is not configured (${status.missing.join(", ")})`);
    err.code = "MAIL_NOT_CONFIGURED";
    throw err;
  }

  return nodemailer.createTransport({
    host: "smtp.gmail.com",
    port: 587,
    secure: false,
    auth: {
      user: process.env.SMTP_EMAIL,
      pass: process.env.SMTP_PASSWORD,
    },
    connectionTimeout: 10000,
    greetingTimeout: 10000,
    socketTimeout: 10000,
  });
}

export async function sendInquiryEmail({ name, email, phone, company, service, budget, message }) {
  const transporter = createMailTransporter();

  const timestamp = new Date().toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    dateStyle: "full",
    timeStyle: "long",
  });

  const emailBody = `
NEW PROJECT INQUIRY
${"=".repeat(50)}

Name:         ${name}
Email:        ${email}
Phone:        ${phone}
Company:      ${company || "N/A"}
Service Tier: ${SERVICE_TIER_LABELS[service] || service}
Budget:       ${budget}
${"=".repeat(50)}

Message:
${message}

${"=".repeat(50)}
Submitted At: ${timestamp}
  `.trim();

  await transporter.sendMail({
    from: `"${name} via MistHustlers" <${process.env.SMTP_EMAIL}>`,
    replyTo: email,
    to: process.env.EMAIL_TO,
    subject: "New Project Inquiry — MistHustlers",
    text: emailBody,
  });
}

function getLeadQualityEmoji(score) {
  if (score >= 80) return "🟢 HOT";
  if (score >= 60) return "🔵 QUALIFIED";
  if (score >= 40) return "🟡 NURTURE";
  if (score < 0) return "⛔ SPAM";
  return "⚪ LOW PRIORITY";
}

export async function sendChatbotLeadEmail({ lead, conversation }) {
  const transporter = createMailTransporter();

  const timestamp = new Date().toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    dateStyle: "full",
    timeStyle: "long",
  });

  const transcript = conversation
    .map(
      (msg) =>
        `[${new Date(msg.createdAt).toLocaleTimeString("en-IN", { timeZone: "Asia/Kolkata" })}] ${msg.role === "user" ? "🧑 Customer" : "🎙️ ARIA"}: ${msg.content}`
    )
    .join("\n\n");

  const leadQuality = getLeadQualityEmoji(lead.leadScore);

  const emailBody = `
══════════════════════════════════════
  ARIA CHATBOT — LEAD CONVERSATION
══════════════════════════════════════

${leadQuality}  |  Score: ${lead.leadScore}/100  |  Category: ${lead.leadCategory}

──────────────────────────────────────
  LEAD DETAILS
──────────────────────────────────────

Name:              ${lead.name || "Not shared"}
Phone:             ${lead.phone || "Not shared"}
Email:             ${lead.email || "Not shared"}
Company:           ${lead.company || "Not shared"}
Service Interest:  ${lead.serviceInterest || "Not specified"}
Budget:            ${lead.budget || "Not shared"}
Timeline:          ${lead.timeline || "Not shared"}
Goal:              ${lead.goal || "Not specified"}
Diagnosis:         ${lead.notes || "Standard discovery"}
Status:            ${lead.status || "new"}

──────────────────────────────────────
  QUALITY ASSESSMENT
──────────────────────────────────────

Lead Score:        ${lead.leadScore}/100
Category:          ${lead.leadCategory}
Conversion Potential: ${lead.leadScore >= 80 ? "Very High — Contact immediately" : lead.leadScore >= 60 ? "High — Contact within 24 hours" : lead.leadScore >= 40 ? "Medium — Nurture sequence" : "Low — Monitor"}

──────────────────────────────────────
  FULL CONVERSATION TRANSCRIPT
──────────────────────────────────────

${transcript}

──────────────────────────────────────
  GENERATED BY ARIA — MistHustlers Sales Consultant
  Submitted At: ${timestamp}
══════════════════════════════════════
  `.trim();

  await transporter.sendMail({
    from: `"ARIA Chatbot" <${process.env.SMTP_EMAIL}>`,
    replyTo: lead.email || process.env.SMTP_EMAIL,
    to: process.env.EMAIL_TO,
    subject: `${leadQuality} ARIA Lead: ${lead.name || "Unknown"} — ${lead.serviceInterest || "General"} (Score: ${lead.leadScore})`,
    text: emailBody,
  });
}

